package com.bernkastel5.haqomu.lookup

/**
 * Извлечение словарного запроса из выделенного текста (Ф1).
 *
 * Правила: берётся ПЕРВАЯ последовательность арабских букв вместе с огласовкой;
 * латиница, цифры и знаки препинания — разделители. Так ««الاستقلال.»» и «الطفل، عاد»
 * превращаются в «الاستقلال» и «الطفل». Если арабского текста нет — null, попап
 * показывает честную плашку вместо поиска случайного слова.
 */
object LookupQuery {

    // Буквы арабского блока + огласовка + татвиль; арабская пунктуация (، ؛ ؟ ؝ …)
    // и арабско-индийские цифры — разделители, не части слова.
    private val ARABIC_RUN = Regex(
        "(?:[\\u0620-\\u063F\\u0641-\\u064A\\u066E-\\u066F\\u0671-\\u06D3\\u06D5\\u06EE-\\u06EF]" +
            "|[\\u0610-\\u061A\\u064B-\\u065F\\u0670\\u0640])+"
    )

    fun extract(raw: String?): String? {
        val text = raw?.trim() ?: return null
        if (text.isEmpty()) return null
        return ARABIC_RUN.find(text)?.value?.takeIf { it.isNotBlank() }
    }
}
