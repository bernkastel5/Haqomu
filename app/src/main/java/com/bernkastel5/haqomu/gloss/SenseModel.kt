package com.bernkastel5.haqomu.gloss

/**
 * Модель разрешения смыслов (Ф10) в самом общем виде: «подходит ли это толкование
 * этому предложению». Интерфейс существует ради двух целей:
 *
 *  1. вся логика выбора смысла (порог 0.3, перестановка внутри статьи) живёт в
 *     [SenseRanking] и тестируется на JVM без ONNX;
 *  2. если модель не установлена, не загрузилась или упала — попап работает как раньше
 *     (словарный порядок), потому что [SenseResolver] умеет работать без модели.
 */
interface SenseModel : AutoCloseable {

    /** Имя для показа в попапе и настройках («ArabGlossBERT int8»). */
    val name: String

    /**
     * Вероятность класса «подходит» для каждой пары «предложение — толкование».
     * Порядок результата совпадает с порядком [definitions]; пустой вход — пустой выход.
     */
    fun score(sentence: String, definitions: List<String>): DoubleArray

    override fun close() {}
}
